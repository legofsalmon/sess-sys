/**
 * What changed in each version of the app, in plain words, newest first
 * (ADR 0071). Admin › What's changed reads it, and the top entry's number
 * is the app's version.
 *
 * Every change to the app adds an entry here, at the top, with the next
 * number: the middle number up for something new a person can use (1.4.0
 * to 1.5.0), the last up for a fix or a change that only makes things
 * work better (1.5.0 to 1.5.1). The first number went to 1 when the real
 * calendars came in on 16 October 2026. Changes to the plans and docs
 * alone don't get one.
 */

export interface Release {
  /** major.minor.patch, one more than the entry below it. */
  version: string
  /** The day it was merged, YYYY-MM-DD. */
  date: string
  /** What changed, in a few words: the heading of the entry. */
  title: string
  /** A sentence or two a member of the office would follow, without code words. */
  what: string
  /** The pull requests it came in, for more detail. */
  prs: number[]
  /** The decision records (ADRs) behind it, if any. */
  adrs?: number[]
}

